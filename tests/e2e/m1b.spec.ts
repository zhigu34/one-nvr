 await page.goto('/channels')
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'导出摄像头配置',exact:true}).click();const download=await downloadPromise
 expect(download.suggestedFilename()).toBe('one-nvr-channels.json')
 const exported=readFileSync((await download.path())!)
 await page.getByRole('button',{name:'批量导入',exact:true}).click()
