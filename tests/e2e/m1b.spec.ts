 await page.getByRole('button',{name:'历史与诊断',exact:true}).click()
 await page.getByRole('button',{name:'查看账号密码',exact:true}).click()
 await expect(page.getByLabel('已保存密码',{exact:true})).toHaveValue('fixture-source-password')
